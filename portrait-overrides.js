function applyPortraitOverrides(root = document) {
  const map = window.HENCHBOUND_PORTRAIT_OVERRIDES || {};
  root.querySelectorAll("img[alt]").forEach(img => {
    const src = map[img.alt];
    if (src && img.src !== src) img.src = src;
  });
}

